"""Closure resolver (STRIP_PLAN_V2.md §5 step 2, issue #7).

Fixpoint over the union of define sets: build the current file set once per define set, map each
compile error to the crypto/src files that declare the missing symbol, add them, repeat until no set
adds a file or a namespace. Seeds: the roots (files outside crypto/src) plus crypto/src/turbo/.

- Index (index.py): types by (namespace, name, arity), nested types -> outer file, partial types as
  one unit, a separate extension-method index.
- Resolution in C# lookup order: the erroring file's enclosing namespaces from innermost outward,
  each followed by the usings of that namespace declaration, then the global namespace and the
  compilation-unit usings. The first level with a candidate wins; several candidates are added
  only on a same-level tie. A candidate whose files are already compiled is not visible in this
  define set (the error persists), so lookup continues outward, as C# does.
  CS0246/CS0103/CS0305/CS0308 by name+arity, CS0426 by outer type, CS0234 by namespace+name (never
  for `using X.Y;` lines: the stubs handle those), CS1061/CS1501 through the extension index.
- Namespace stubs: every iteration, `namespace X { }` for every crypto/src namespace a kept using
  names (plus namespaces hit by qualified names), written to the work directory, never crypto/src.
  At the fixpoint they are pruned to namespaces a kept using names and no kept file declares, and
  every set is rebuilt; the survivors are <work>/_TurboNamespaceStubs.cs (shipped as
  Lib/_TurboNamespaceStubs.cs by the packaging step, #9).
- Deny list and referrer sweep (#8, deny.py): at the fixpoint the strip/deny.txt globs mark the
  closure files to deny (seeds exempt). Every set is then built once more without them (stubs
  re-pruned for the kept files); every kept file that fails is a referrer needing a cut, and its
  errors resolve to the denied files they need: the complete list, not the first referrer the
  loop recorded in prov.json.
- Fail checks run at the fixpoint only (CHECKS): unresolved errors, a stalled loop, errors that
  only the pruned stubs cause, deny hits (one line per kept referrer), sweep errors no denied file
  explains, a budget overrun (strip/budget.txt; no cap while it is absent). `--report` logs
  failures instead of failing.

Outputs in --work: closure_files.json (sorted crypto/src-relative paths), prov.json
({file: ["referrer:Name", ...]}, first referrers only), _TurboNamespaceStubs.cs, closure_report.json
(also the denied files, the sweep referrers and the kept per-directory counts).
The define assertion (defines.py) runs on the first and the final build of every set.
"""

