REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
STUBS_FILE = "_nsstubs.cs"
SHIPPED_STUBS = "_TurboNamespaceStubs.cs"
STUB_HEADER = "// Generated by strip/tool/closure.py: namespaces named by kept usings that no kept file declares.\n"

_ERROR = re.compile(
    r"^\s*(?P<path>.+?)\((?P<line>\d+),(?P<col>\d+)\): error (?P<code>CS\d{4}): (?P<msg>.*?)(?: \[[^\]]*\])?\s*$"
)
_QUOTED = re.compile(r"'([^']+)'")
TYPE_CODES = ("CS0246", "CS0103", "CS0305", "CS0308")


@dataclass(frozen=True, order=True)
class BuildError:
    path: str
    line: int
    col: int
    code: str
    msg: str

    def __str__(self):
        return f"{self.path}({self.line},{self.col}): {self.code}: {self.msg}"


def parse_errors(output):
    errs = set()
    for line in output.splitlines():
        m = _ERROR.match(line)
        if m:
            errs.add(BuildError(m["path"], int(m["line"]), int(m["col"]), m["code"], m["msg"]))
    return errs


def strip_generics(name):
    prev = None
    while prev != name:
        prev, name = name, re.sub(r"<[^<>]*>", "", name)
    return name


def split_generic(name):
    """'Foo<,>' -> ('Foo', 2); 'Foo' -> ('Foo', 0)."""
    if "<" in name:
        base, args = name.split("<", 1)
        return base, args.rsplit(">", 1)[0].count(",") + 1
    return name, 0


def source_arity(line_text, name, col):
    """Generic arity written after `name` at or after column `col` (1-based) of a source line."""
    m = re.compile(r"(?<![\w.])" + re.escape(name) + r"\s*<").search(line_text, max(col - 1, 0))
    if not m:
        m = re.compile(r"\b" + re.escape(name) + r"\s*<").search(line_text)
    if not m:
        return 0
    depth, commas = 0, 0
    for c in line_text[m.end() - 1 :]:
        if c == "<":
            depth += 1
        elif c == ">":
            depth -= 1
            if depth == 0:
                return commas + 1
        elif c == "," and depth == 1:
            commas += 1
    return 0


@dataclass
class Level:
    kind: str  # "ns" | "using"
    ns: str = ""
    usings: list = field(default_factory=list)
    aliases: dict = field(default_factory=dict)


def lookup_levels(info, line):
    """C# lookup order for a simple name at `line` of `info`."""
    chain = sorted((d for d in info.namespaces if d.start <= line <= d.end), key=lambda d: (d.start, -d.end))
    decls = {d.name: d for d in chain}
    levels = []

    def using_level(usings):
        lv = Level("using")
        for u in usings:
            if u.kind == "ns":
                lv.usings.append(u.target)
            elif u.kind == "alias":
                lv.aliases[u.alias] = u.target
        return lv

    for prefix in namespace_prefixes(chain[-1].name if chain else ""):
        levels.append(Level("ns", prefix))
        d = decls.get(prefix)
        if d is not None:
            levels.append(using_level(u for u in info.usings if u.scope == prefix and d.start <= u.line <= d.end))
    levels.append(Level("ns", ""))
    levels.append(using_level(u for u in info.usings if u.scope == ""))
    return levels


@dataclass
class Resolution:
    files: set
    namespaces: set
    keys: list
    tie: bool = False


class Resolver:
    """Maps one compile error to the files (and namespaces) that declare the missing symbol."""

    def __init__(self, index, src, repo=REPO):
        self.index = index
        self.src = os.path.abspath(src)
        self.repo = repo
        self._outside = {}
        self._lines = {}

    def rel(self, path):
        """crypto/src-relative path for files under src, else None."""
        p = os.path.abspath(path)
        if p.startswith(self.src + os.sep):
            return os.path.relpath(p, self.src).replace(os.sep, "/")
        return None

    def display(self, path):
        rel = self.rel(path)
        return rel if rel is not None else os.path.relpath(os.path.abspath(path), self.repo).replace(os.sep, "/")

    def info(self, path):
        rel = self.rel(path)
        if rel is not None:
            return self.index.files.get(rel)
        p = os.path.abspath(path)
        if p not in self._outside:
            self._outside[p] = scan_file(p) if os.path.isfile(p) else None
        return self._outside[p]

    def line_text(self, path, line):
        p = os.path.abspath(path)
        if p not in self._lines:
            try:
                with open(p, encoding="utf-8-sig", errors="replace") as f:
                    self._lines[p] = f.read().splitlines()
            except OSError:
                self._lines[p] = []
        lines = self._lines[p]
        return lines[line - 1] if 0 < line <= len(lines) else ""

    def _missing(self, keys, present):
        return [k for k in keys if k in self.index.types and not set(self.index.types[k]) <= present]

    def resolve_type(self, levels, name, arity, present, known_ns):
        for lv in levels:
            keys, nss = [], []
            if lv.kind == "ns":
                keys = self._missing([(lv.ns, name, arity)], present)
                candidate = full_name(lv.ns, name)
                if arity == 0 and candidate in self.index.namespaces and candidate not in known_ns:
                    nss.append(candidate)
            else:
                cand = [(u, name, arity) for u in lv.usings]
                target = lv.aliases.get(name) if arity == 0 else None
                if target is not None:
                    if target in self.index.namespaces:
                        if target not in known_ns:
                            nss.append(target)
                    else:
                        tns, _, tname = strip_generics(target).rpartition(".")
                        cand.append((tns, tname, split_generic(target.rsplit(".", 1)[-1])[1]))
                keys = self._missing(cand, present)
            if keys or nss:
                return self._resolution(keys, nss)
        return None

    def resolve_extension(self, levels, method, present):
        entries = self.index.extensions.get(method, [])
        for lv in levels:
            spaces = {lv.ns} if lv.kind == "ns" else set(lv.usings)
            files = {f for ns, f in entries if ns in spaces and f not in present}
            if files:
                res = Resolution(set(), set(), [])
                for f in sorted(files):
                    res.files |= self.index.partial_unit(f)
                return res
        return None

    def _resolution(self, keys, nss):
        res = Resolution(set(), set(nss), sorted(keys), tie=len(set(keys)) + len(nss) > 1)
        for key in keys:
            for f in self.index.types[key]:
                res.files |= self.index.partial_unit(f)
        return res

    def resolve(self, err, present, known_ns):
        """(Resolution or None, symbol name)."""
        info = self.info(err.path)
        q = _QUOTED.findall(err.msg)
        if info is None or not q:
            return None, ""
        if err.code in TYPE_CODES:
            name, arity = split_generic(strip_generics(q[0]).rsplit(".", 1)[-1] if err.code != "CS0246" else q[0])
            if err.code in ("CS0305", "CS0308"):
                arity = source_arity(self.line_text(err.path, err.line), name, err.col)
            elif err.code == "CS0103":
                arity = 0
            return self.resolve_type(lookup_levels(info, err.line), name, arity, present, known_ns), name
        if err.code == "CS0234" and len(q) >= 2:
            if any(u.line == err.line and u.kind == "ns" for u in info.usings):
                return None, q[0]  # `using X.Y;` lines are the stubs' job, never a type lookup
            name, arity = split_generic(q[0])
            ns = strip_generics(q[1])
            keys = self._missing([(ns, name, arity)], present)
            candidate = full_name(ns, name)
            nss = [candidate] if arity == 0 and candidate in self.index.namespaces and candidate not in known_ns else []
            return (self._resolution(keys, nss) if keys or nss else None), name
        if err.code == "CS0426" and len(q) >= 2:
            name = q[0]
            keys = self._missing(self.index.by_full.get(strip_generics(q[1]) + "." + name, []), present)
            return (self._resolution(keys, []) if keys else None), name
        if err.code in ("CS1061", "CS1501"):
            method = q[1] if err.code == "CS1061" and len(q) >= 2 else q[0]
            return self.resolve_extension(lookup_levels(info, err.line), method, present), method
        return None, ""


def using_namespaces(infos, index):
    """crypto/src namespaces named by the usings of `infos` (namespace usings and namespace aliases)."""
    names = set()
    for info in infos:
        for u in info.usings:
            if u.kind in ("ns", "alias") and u.target in index.namespaces:
                names.add(u.target)
    return names


def declared_namespaces(infos):
    names = set()
    for info in infos:
        for d in info.namespaces:
            names.update(namespace_prefixes(d.name))
    return names


def prune_stubs(using_ns, declared):
    """Stubs that survive the fixpoint: named by a kept using, declared by no kept file; a stub
    that is the ancestor of another survivor is implied by it and dropped."""
    survivors = {n for n in using_ns if n and n not in declared}
    return sorted(n for n in survivors if not any(o.startswith(n + ".") for o in survivors))


def render_stubs(namespaces):
    return STUB_HEADER + "".join(f"namespace {n} {{ }}\n" for n in sorted(namespaces))


class BuildFailure(Exception):
    pass


class DotnetBuilder:
    """One copy of Closure.csproj per define set under <work>/sets/<set>; restore once, then
    `dotnet build --no-restore`. The first and the final build of a set carry the binlog define
    assertion."""

    def __init__(self, work, csproj, sets, dotnet="dotnet", log=print):
        self.work = work
        self.csproj = csproj
        self.sets = sets  # name -> [defines]
        self.dotnet = dotnet
        self.log = log
        self.asserted = set()

    def set_dir(self, name):
        return os.path.join(self.work, "sets", name)

    def _write_props(self, name, files):
        props = defines_mod.render_props(defines_mod.tfm_for_set(name), self.sets[name], files)
        with open(os.path.join(self.set_dir(name), "Closure.props"), "w", encoding="utf-8") as f:
            f.write(props)

    def prepare(self, restore=True):
        for name in self.sets:
            d = self.set_dir(name)
            os.makedirs(d, exist_ok=True)
            shutil.copyfile(self.csproj, os.path.join(d, "Closure.csproj"))
            self._write_props(name, [])
            if restore:
                r = subprocess.run(
                    [self.dotnet, "restore", os.path.join(d, "Closure.csproj"), "-nologo", "-v:q"],
                    capture_output=True,
                    text=True,
                )
                if r.returncode != 0:
                    raise BuildFailure(f"[{name}] dotnet restore failed:\n{(r.stdout + r.stderr)[-3000:]}")

    def build(self, name, files, assert_defines=False):
        d = self.set_dir(name)
        self._write_props(name, files)
        cmd = [self.dotnet, "build", os.path.join(d, "Closure.csproj"), "--no-restore", "-nologo", "-v:q"]
        cmd.append("-clp:NoSummary")
        binlog = os.path.join(d, "defines.binlog")
        if assert_defines:
            cmd += ["--no-incremental", f"-bl:{binlog}"]
        r = subprocess.run(cmd, capture_output=True, text=True)
        errors = parse_errors(r.stdout)
        if r.returncode != 0 and not errors:
            raise BuildFailure(f"[{name}] dotnet build failed without compile errors:\n{(r.stdout + r.stderr)[-3000:]}")
        if assert_defines:
            self.assert_defines(name, binlog)
        return errors

    def assert_defines(self, name, binlog):
        log = binlog + ".log"
        r = subprocess.run(
            [self.dotnet, "msbuild", binlog, "-noConsoleLogger", "-fl", f"-flp:logfile={log};verbosity=normal"],
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            raise BuildFailure(f"[{name}] binlog replay failed:\n{(r.stdout + r.stderr)[-2000:]}")
        with open(log, encoding="utf-8", errors="replace") as f:
            actual = defines_mod.csc_defines(f.read())
        problems = defines_mod.check_defines(name, self.sets[name], actual)
        if problems:
            raise defines_mod.DefineError("; ".join(problems))
        self.log(f"[{name}] define assertion ok: csc /define: == {sorted(actual)}")


@dataclass
class ClosureResult:
    sets: list
    files: list = field(default_factory=list)
    stubs: list = field(default_factory=list)
    prov: dict = field(default_factory=dict)
    ties: list = field(default_factory=list)
    iterations: list = field(default_factory=list)
    loop_errors: dict = field(default_factory=dict)  # set -> errors of the last loop build
    final_errors: dict = field(default_factory=dict)  # set -> errors of the pruned-stub rebuild
    stalled: bool = False

    def to_json(self):
        return {
            "sets": self.sets,
            "files": self.files,
            "stubs": self.stubs,
            "ties": self.ties,
            "iterations": self.iterations,
            "stalled": self.stalled,
            "unresolved": {s: [str(e) for e in sorted(v)] for s, v in self.final_errors.items()},
        }


def run_closure(index, resolver, builder, set_names, seed_files, root_files, stub_path, max_iter=100, log=print):
    """Fixpoint over the union of define sets. `seed_files` are crypto/src-relative; `root_files`
    absolute paths outside crypto/src (always compiled, never part of closure_files.json)."""
    src = resolver.src
    files = set()
    for f in seed_files:
        files |= index.partial_unit(f)
    roots = [resolver.info(p) for p in root_files]
    roots = [r for r in roots if r is not None]
    extra_ns = set()
    prov = {}
    result = ClosureResult(list(set_names))

    def compile_list(stub_file):
        return sorted(os.path.join(src, f) for f in files) + sorted(root_files) + [stub_file]

    def kept_infos():
        return [index.files[f] for f in sorted(files) if f in index.files] + roots

    def write_stubs(path, names):
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(render_stubs(names))

    errors = {}
    for it in range(1, max_iter + 1):
        t0 = time.time()
        stubs = using_namespaces(kept_infos(), index) | extra_ns
        write_stubs(stub_path, stubs)
        known_ns = stubs | declared_namespaces(kept_infos())
        errors = {s: builder.build(s, compile_list(stub_path), assert_defines=(it == 1)) for s in set_names}
        add, new_ns = set(), set()
        for s in set_names:
            for err in sorted(errors[s]):
                res, name = resolver.resolve(err, files, known_ns)
                if res is None:
                    continue
                new_files = res.files - files
                add |= new_files
                new_ns |= res.namespaces - known_ns
                referrer = resolver.display(err.path)
                for f in new_files:
                    prov.setdefault(f, set()).add(f"{referrer}:{name}")
                if res.tie:
                    tie = {"referrer": referrer, "name": name, "keys": ["|".join(map(str, k)) for k in res.keys]}
                    if tie not in result.ties:
                        result.ties.append(tie)
        counts = {s: len(errors[s]) for s in set_names}
        result.iterations.append({"it": it, "files": len(files), "errors": counts, "added": len(add)})
        log(f"it{it}: files={len(files)} errors={counts} +{len(add)} files +{len(new_ns)} ns ({time.time() - t0:.0f}s)")
        if not add and not new_ns:
            break
        files |= add
        extra_ns |= new_ns
    else:
        result.stalled = True
        log(f"no fixpoint after {max_iter} iterations")

    result.loop_errors = errors
    result.stubs = prune_stubs(using_namespaces(kept_infos(), index), declared_namespaces(kept_infos()))
    write_stubs(stub_path, result.stubs)
    result.final_errors = {s: builder.build(s, compile_list(stub_path), assert_defines=True) for s in set_names}
    result.files = sorted(files)
    result.prov = {k: sorted(v) for k, v in sorted(prov.items())}
    return result


def check_stalled(result):
    return ["closure did not reach a fixpoint"] if result.stalled else []


def check_unresolved(result):
    out = []
    for s in result.sets:
        out += [f"[{s}] unresolved: {e}" for e in sorted(result.final_errors.get(s, ()))]
    return out


def check_pruning(result):
    if result.stalled:  # the last batch of files was never built in the loop
        return []
    out = []
    for s in result.sets:
        extra = set(result.final_errors.get(s, ())) - set(result.loop_errors.get(s, ()))
        out += [f"[{s}] error only with pruned stubs: {e}" for e in sorted(extra)]
    return out


# Fail checks, run once at the fixpoint; each takes the ClosureResult and returns failure lines.
# #8 adds the deny-hit check (naming the kept referrer), the referrer sweep and the budget here.
CHECKS = [check_stalled, check_unresolved, check_pruning]


def collect_seeds(src, seeds):
    """crypto/src-relative .cs files for --seed entries (files or directories under src)."""
    out = set()
    for s in seeds:
        p = os.path.join(src, s)
        if os.path.isdir(p):
            for d, dirs, fs in os.walk(p):
                dirs[:] = [x for x in dirs if x not in ("bin", "obj")]
                out |= {os.path.relpath(os.path.join(d, f), src).replace(os.sep, "/") for f in fs if f.endswith(".cs")}
        elif os.path.isfile(p) and p.endswith(".cs"):
            out.add(os.path.relpath(p, src).replace(os.sep, "/"))
        else:
            raise SystemExit(f"--seed {s}: no such .cs file or directory under {src}")
    return sorted(out)


def collect_roots(dirs):
    out = []
    for r in dirs:
        if os.path.isfile(r) and r.endswith(".cs"):
            out.append(os.path.abspath(r))
            continue
        if not os.path.isdir(r):
            raise SystemExit(f"--roots {r}: not a directory or .cs file")
        for d, sub, fs in os.walk(r):
            sub[:] = sorted(x for x in sub if x not in ("bin", "obj"))
            out += [os.path.abspath(os.path.join(d, f)) for f in sorted(fs) if f.endswith(".cs")]
    return out


def is_inside(path, parent):
    path, parent = os.path.realpath(path), os.path.realpath(parent)
    return path == parent or path.startswith(parent + os.sep)


def parse_args(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", default=os.path.join(REPO, "crypto", "src"))
    ap.add_argument("--roots", action="append", default=[], help="root .cs files/dirs outside crypto/src")
    ap.add_argument("--seed", action="append", default=[], help="extra crypto/src-relative seed file or dir")
    ap.add_argument("--defines", default=os.path.join(REPO, "strip", "unity-defines.txt"))
    ap.add_argument("--set", dest="sets", action="append", default=[], help="only these define sets")
    ap.add_argument("--csproj", default=os.path.join(REPO, "strip", "Closure.csproj"))
    ap.add_argument("--work", default=os.path.join(REPO, "strip", "work"))
    ap.add_argument("--max-iter", type=int, default=100)
    ap.add_argument("--report", action="store_true", help="log fail checks instead of failing")
    ap.add_argument("--no-restore", action="store_true")
    ap.add_argument("--dotnet", default="dotnet")
    return ap.parse_args(argv)


def main(argv=None):
    a = parse_args(sys.argv[1:] if argv is None else argv)
    src = os.path.abspath(a.src)
    work = os.path.abspath(a.work)
    if is_inside(work, src):
        print(f"--work {work} is inside {src}: the closure never writes to crypto/src", file=sys.stderr)
        return 2
    all_sets = defines_mod.load_unity_defines(a.defines)
    unknown = [s for s in a.sets if s not in all_sets]
    if unknown:
        print(f"unknown define set(s) {unknown}; {a.defines} has {list(all_sets)}", file=sys.stderr)
        return 2
    sets = {s: all_sets[s] for s in (a.sets or all_sets)}
    seeds = a.seed[:]
    if os.path.isdir(os.path.join(src, "turbo")):
        seeds.append("turbo")
    seed_files = collect_seeds(src, seeds)
    root_files = collect_roots(a.roots)
    if any(is_inside(p, src) for p in root_files):
        print("--roots must be outside crypto/src (use --seed for crypto/src files)", file=sys.stderr)
        return 2
    if not seed_files and not root_files:
        print("nothing to seed: pass --roots and/or --seed", file=sys.stderr)
        return 2

    os.makedirs(work, exist_ok=True)
    t0 = time.time()
    index = build_index(src)
    print(f"index: {len(index.files)} files, {len(index.types)} types ({time.time() - t0:.0f}s)")
    builder = DotnetBuilder(work, os.path.abspath(a.csproj), sets, dotnet=a.dotnet)
    try:
        builder.prepare(restore=not a.no_restore)
        result = run_closure(
            index, Resolver(index, src), builder, list(sets), seed_files, root_files, os.path.join(work, STUBS_FILE), a.max_iter
        )
    except defines_mod.DefineError as e:
        print(f"DEFINE ASSERTION FAILED: {e}", file=sys.stderr)
        return 2
    except BuildFailure as e:
        print(f"BUILD FAILURE: {e}", file=sys.stderr)
        return 3

    def dump(name, obj):
        with open(os.path.join(work, name), "w", encoding="utf-8") as f:
            json.dump(obj, f, indent=1, sort_keys=True)
            f.write("\n")

    dump("closure_files.json", result.files)
    dump("prov.json", result.prov)
    dump("closure_report.json", result.to_json())
    with open(os.path.join(work, SHIPPED_STUBS), "w", encoding="utf-8") as f:
        f.write(render_stubs(result.stubs))
    print(f"fixpoint: {len(result.files)} files, {len(result.stubs)} stubs, {len(result.ties)} same-level ties")
    for tie in result.ties:
        print(f"  tie: {tie['referrer']}: {tie['name']} -> {tie['keys']}")

    failures = [line for check in CHECKS for line in check(result)]
    for line in failures:
        print(("REPORT " if a.report else "FAIL ") + line)
    if not failures:
        print("CLEAN")
        return 0
    return 0 if a.report else 1


